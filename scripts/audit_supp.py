"""
Recompute every number and claim in the supplement text (paper/supp_body2.tex) from the result files and check that
the text states it as written. Prints OK / MISMATCH per item. Read-only. Tables are generated by make_supp.py from the
same files and need no check here.

    python -X utf8 scripts/audit_supp.py <path to supp_body2.tex>
"""
import json
import re
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_paper_assets as m  # noqa: E402
import make_supp as s  # noqa: E402

tex = re.sub(r'\s+', ' ', open(sys.argv[1], encoding='utf8').read())
ok = bad = 0


def report(good, label, shown, text):
    global ok, bad
    present = text in tex
    good = good and present
    ok += good
    bad += not good
    print(f"{'OK      ' if good else 'MISMATCH'} {label}: data {shown} | text '{text}'"
          + ('' if present else '  <- text not in supplement'))


def check(label, value, text, fmt):
    shown = fmt.format(value)
    report(shown in text, label, shown, text)


def claim(label, holds, text, detail=''):
    report(bool(holds), label, f'{holds} {detail}'.strip(), text)


R, SUPP, ENC = s.R, s.SUPP, list(s.ENC)
TCC1, TCC1K4, TCC2 = s.TCC1, s.TCC1K4, s.TCC2

print('== B.1 redundancy')
red = json.load(open(SUPP / 'redundancy.json'))
allt = [x for ds in red for e in red[ds] for x in red[ds][e]['1']['temporal_pooled']]
check('temporal min', min(allt), '4.5--46.2\\% across datasets', '{:.1f}--')
check('temporal max', max(allt), '4.5--46.2\\% across datasets', '--{:.1f}')
wins = {(ds, e): sum(red[ds][e]['1']['temporal_pooled'][l] < red[ds][e]['1']['cross_layer_mean'][l] for l in (1, 3, 5, 7))
        for ds in red for e in red[ds]}
claim('temporal beats cross-layer in 3 of 4 modules everywhere', all(v == 3 for v in wins.values()),
      'leaves less energy in three of the four modules on every dataset and backbone', str(wins))
for ds, txt in (('sintel', '29.9 to 25.5\\% (Sintel)'), ('bonn', '13.0 to 12.3\\% (Bonn)'),
                ('scannet', '12.2 to 11.6\\% (ScanNet)')):
    a = red[ds]['vits']['1']
    check(f'{ds} temporal mean', float(np.mean(a['temporal_mean'])), txt, '{:.1f} to')
    check(f'{ds} affine fit mean', float(np.mean(a['temporal_fit_mean'])), txt, 'to {:.1f}')

print('== B.2 error through the head')
cfgs = ['int2-g16', 'int2-g64-asym', TCC1, TCC2]
below, exceptions = True, []
for ds in ('sintel', 'bonn'):
    for e in ('vits', 'vitl'):
        X = s.J(SUPP / f'moderr_{ds}_{e}.json')
        for c in cfgs:
            below &= X[c]['fid_rel_dev_pct'] < min(X[c]['module_rel_err_pct'].values())
        for i, a in enumerate(cfgs):
            for b in cfgs[i + 1:]:
                ma, mb = X[a]['module_rel_err_pct'], X[b]['module_rel_err_pct']
                dsign = np.sign(X[a]['fid_rel_dev_pct'] - X[b]['fid_rel_dev_pct'])
                if any(np.sign(ma[k] - mb[k]) != dsign for k in ma):
                    exceptions.append((ds, e, a, b))
claim('depth deviation below every module error', below, 'the depth deviation is lower than the error of every module')
claim('only exception: Sintel ViT-L, INT2 asym vs TCC-1',
      exceptions == [('sintel', 'vitl', 'int2-g64-asym', TCC1)], 'exception (Sintel, ViT-L: \\ours-1 has lower module errors',
      str(exceptions))

print('== B.3 decoding cost vs K')
d = json.load(open(SUPP / 'timing_k.json'))
g = defaultdict(list)
for r in (d['results'] if isinstance(d, dict) else d):
    g[(r['encoder'], r['config'])].append(r)
spread = max(max(st.median(x['ms_median'] for x in g[(e, f'int4-g16::d{k}:bin-g16')]) for k in (2, 4, 8, 16, 32))
             - min(st.median(x['ms_median'] for x in g[(e, f'int4-g16::d{k}:bin-g16')]) for k in (2, 4, 8, 16, 32))
             for e in ('vits', 'vitl'))
claim('latency spread over K <= 1.2 ms', round(spread, 1) <= 1.2, 'latency stays within 1.2\\,ms', f'{spread:.2f}')
check('cache K=8', g[('vits', 'int4-g16::d8:bin-g16')][0]['cache_mb'], '22.9\\,MB at $K{=}8$', '{:.1f}\\,MB')
check('cache K=32', g[('vits', 'int4-g16::d32:bin-g16')][0]['cache_mb'], '21.7\\,MB at $K{=}32$', '{:.1f}\\,MB')

print('== C.1 flicker and per-frame alignment (Sintel, Bonn)')
okc2 = okk4 = True
for ds in ('bonn', 'sintel'):
    for e in ENC:
        rs = m.pair_rows(ds, e)
        b = m.row(rs, 'fp32')
        rows = {c: m.row(rs, c) for c, _, _ in m.FORMATS}
        okc2 &= all(rows[TCC2][k] <= r[k] for r in rows.values() for k in ('fid_rel_dev_pct', 'fid_flicker_pct'))
        small = [c for c, r in rows.items() if 32 * r['cache_mb'] / b['cache_mb'] <= 2.5 + 1e-9 and c != 'zero']
        okk4 &= min(small, key=lambda c: rows[c]['fid_rel_dev_pct']) == TCC1K4
claim('TCC-2 lowest dev and flicker', okc2, '\\ours-2 has the lowest deviation and flicker of all formats on every backbone, and')
claim('TCC-1 K4 lowest dev at <= 2.5 bits', okk4, '\\ours-1 at $K{=}4$ the lowest among formats of at most 2.5 bits')

print('== C.2 more datasets')
d1 = ar = 0.0
okc2 = True
for name, load in (('bonn5', lambda e: m.seq_rows('bonn5', e)), ('kitti', lambda e: m.seq_rows('kittiseq', e)),
                   ('scannet', lambda e: s.J(s.SCN / f'scannet_{e}.json'))):
    for e in ENC:
        X = load(e)
        b = X['fp32']
        d1 = max(d1, max(abs(X[c]['delta1_seq'] - b['delta1_seq']) for c in (TCC1, TCC1K4, TCC2)))
        ar = max(ar, max(abs(X[c]['abs_rel_seq'] - b['abs_rel_seq']) for c in (TCC1, TCC1K4, TCC2)))
        rows = [c for c, _ in s.ROWS if c != 'fp32' and c in X]
        okc2 &= all(X[TCC2][k] <= X[c][k] for c in rows for k in ('fid_rel_dev_pct', 'fid_flicker_pct'))
claim('delta1 within 0.002', d1 <= 0.002, 'keep $\\delta_1$ within 0.002 and AbsRel within 0.001', f'{d1:.4f}')
claim('AbsRel within 0.001', ar <= 0.001, 'keep $\\delta_1$ within 0.002 and AbsRel within 0.001', f'{ar:.4f}')
claim('TCC-2 lowest dev and flicker (3 datasets)', okc2,
      'and \\ours-2 has the lowest deviation and flicker of all formats on every backbone.')

print('== C.3 bootstrap')
boot = json.load(open(R / 'paper_bootstrap.json'))
check('resamples', f"{boot['n_boot']:,}".replace(',', '{,}'), 'interval from 20{,}000 paired bootstrap', '{}')

print('== C.4 Bonn per scene')
okv = all(m.row(m.pair_rows('bonn', e), TCC1)['per_scene'][x]['fid_rel_dev'] < m.row(m.pair_rows('bonn', e), 'int2-g64-asym')['per_scene'][x]['fid_rel_dev']
          and m.row(m.pair_rows('bonn', e), TCC2)['per_scene'][x]['fid_rel_dev'] < m.row(m.pair_rows('bonn', e), 'int2-g32-asym')['per_scene'][x]['fid_rel_dev']
          for e in ENC for x in m.BONN3)
fb = {r['kv']: r for r in json.load(open(R / 'fidelity_bonn.json'))['results']}
dv = lambda k, x: fb[k]['per_sequence'][x]['fid_rel_dev_pct']
seqs = list(fb['delta:int4:bin:8']['per_sequence'])
oks = all(dv('delta:int4:bin:8', x) < min(dv('plain:a2g64', x), dv('kivi:2:64', x)) and
          dv('delta:int4:a2g64:8', x) < dv('plain:a2g32', x) for x in seqs)
claim('VDA: TCC beats INT2 on every Bonn scene', okv, 'On every scene and backbone, \\ours-1 deviates less than asymmetric')
claim('StreamVGGT: TCC-1 beats INT2 and KIVI on all 5', oks and len(seqs) == 5, 'KIVI on all five sequences')

print('== C.5 open loop')
base = R / '2026-11-02_streaming' / 'streaming_vda'
rat = [json.load(open(base / f'{ds}_{e}_open.json')) for ds in ('sintel', 'bonn') for e in ENC]
rat = [{r['config']: r for r in x['results']} for x in rat]
rat = [X[c + ':open']['fid_rel_dev_pct'] / X[c]['fid_rel_dev_pct'] for X in rat for c in (TCC1, TCC2)]
check('open-loop ratio min', min(rat), 'deviates 1.7--2.7$\\times$ more', '{:.1f}--')
check('open-loop ratio max', max(rat), 'deviates 1.7--2.7$\\times$ more', '--{:.1f}')

print('== C.6 scene cuts')
Xs = s.J(SUPP / 'splice_scannet_vits.json')
bits = lambda X, c: 32 * X[c]['cache_mb'] / X['fp32']['cache_mb']
