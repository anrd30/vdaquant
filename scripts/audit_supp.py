check('recovery ViT-S (median frames)', rec['vits'], 'after a median of 4.5 (ViT-S) and 9 (ViT-L) frames', 'of {:g} (ViT-S)')
check('recovery ViT-L (median frames)', rec['vitl'], 'after a median of 4.5 (ViT-S) and 9 (ViT-L) frames', 'and {:g} (ViT-L)')
