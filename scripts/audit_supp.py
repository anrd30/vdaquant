check('adaptive dev', Xr['int4-g16::d32:bin-g16:a0.35']['fid_rel_dev_pct'], 'adaptive keyframes by 0.48\\% at 3.14 bits', 'by {:.2f}')
check('adaptive bits (rate)', bits(Xr, 'int4-g16::d32:bin-g16:a0.35'), 'adaptive keyframes by 0.48\\% at 3.14 bits', 'at {:.2f} bits')

